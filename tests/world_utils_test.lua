local world_utils = require "modules.world.world_utils"
local shared_utils = require "modules.world.shared_utils"

describe("get_heading_wind_delta", function()
	test("tailwind", function()
		expect(world_utils.get_heading_wind_delta(0, 0)).to_equal(0)
		expect(world_utils.get_heading_wind_delta(6, 6)).to_equal(0)
	end)
	test("side tailwind", function()
		expect(world_utils.get_heading_wind_delta(0, 1)).to_equal(1)
		expect(world_utils.get_heading_wind_delta(0, 7)).to_equal(1)
	end)
	test("crosswind", function()
		expect(world_utils.get_heading_wind_delta(1, 3)).to_equal(2)
		expect(world_utils.get_heading_wind_delta(1, 7)).to_equal(2)
	end)
	test("side headwind", function()
		expect(world_utils.get_heading_wind_delta(6, 1)).to_equal(3)
		expect(world_utils.get_heading_wind_delta(6, 3)).to_equal(3)
	end)
	test("headwind", function()
		expect(world_utils.get_heading_wind_delta(5, 1)).to_equal(4)
		expect(world_utils.get_heading_wind_delta(2, 6)).to_equal(4)
	end)
end)

describe("get_x_wrap_around", function()
	test("wraps around both ends of the world map", function()
		expect(shared_utils.get_x_wrap_around(2159)).to_equal(2159)
		expect(shared_utils.get_x_wrap_around(0)).to_equal(0)
		expect(shared_utils.get_x_wrap_around(-1)).to_equal(2159)
		expect(shared_utils.get_x_wrap_around(2160)).to_equal(0)
		expect(shared_utils.get_x_wrap_around(2161)).to_equal(1)
	end)
end)

test("get_from_to_accounting_for_wrap_around", function()
	local f = shared_utils.get_from_to_accounting_for_wrap_around
	expect(f(0, 0)).to_equal(0)
	expect(f(0, 1)).to_equal(1)
	expect(f(2, 1)).to_equal(-1)
	expect(f(0, 2159)).to_equal(-1)
	expect(f(2159, 0)).to_equal(1)
	expect(f(1000, 0)).to_equal(-1000)
	expect(f(2000, 0)).to_equal(160)
	expect(f(0, 1080)).to_equal(1080)
end)
